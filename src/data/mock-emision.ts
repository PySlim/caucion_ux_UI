export function loadEmisiones(): OperacionEmision[] {
  if (typeof window === "undefined") return OPERACIONES_INICIALES;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return OPERACIONES_INICIALES;
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) return parsed;
  } catch (e) {
    console.warn("Error loading emisiones from localStorage:", e);
  }
  return OPERACIONES_INICIALES;
}

export function saveEmisiones(items: OperacionEmision[]): void {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(items));
  } catch (e) {
    console.warn("Error saving emisiones to localStorage:", e);
  }
}

export function resetEmisiones(): OperacionEmision[] {
  if (typeof window !== "undefined") {
    try {
      localStorage.removeItem(STORAGE_KEY);
    } catch {}
  }
  return OPERACIONES_INICIALES;
}
